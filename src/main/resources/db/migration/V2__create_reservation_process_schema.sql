CREATE TABLE reservation_process (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_process_id VARCHAR(120) UNIQUE,
    hold_id VARCHAR(120) UNIQUE,
    owner_public_id UUID NOT NULL,
    external_patient_id VARCHAR(100) NOT NULL,
    professional_id BIGINT NOT NULL CHECK (professional_id > 0),
    appointment_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    professional_first_name VARCHAR(100) NOT NULL,
    professional_last_name VARCHAR(100) NOT NULL,
    patient_first_name VARCHAR(100),
    patient_last_name VARCHAR(100),
    status VARCHAR(40) NOT NULL,
    expires_at TIMESTAMPTZ,
    request_event_id VARCHAR(120),
    reservation_id BIGINT UNIQUE,
    result_status VARCHAR(40),
    last_error VARCHAR(1000),
    hold_request_payload TEXT,
    confirm_request_payload TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_reservation_process_slot CHECK (start_time < end_time),
    CONSTRAINT ck_reservation_process_status CHECK (status IN (
        'CREATED', 'HELD', 'WAITING_FOR_PHONE', 'CONFIRMED',
        'REJECTED_RETRYABLE', 'EXPIRED', 'INVALID', 'CANCELLED'
    ))
);

CREATE INDEX ix_reservation_process_owner_created
    ON reservation_process (owner_public_id, created_at DESC);
CREATE INDEX ix_reservation_process_status_expiration
    ON reservation_process (status, expires_at);

CREATE TABLE reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_process_id BIGINT NOT NULL UNIQUE
        REFERENCES reservation_process(id) ON DELETE CASCADE,
    catedra_reservation_id BIGINT UNIQUE,
    owner_public_id UUID NOT NULL,
    external_patient_id VARCHAR(100) NOT NULL,
    professional_id BIGINT NOT NULL,
    appointment_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    professional_first_name VARCHAR(100) NOT NULL,
    professional_last_name VARCHAR(100) NOT NULL,
    patient_first_name VARCHAR(100),
    patient_last_name VARCHAR(100),
    patient_phone VARCHAR(32),
    status VARCHAR(40) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    cancellation_reason VARCHAR(500),
    CONSTRAINT ck_reservation_slot CHECK (start_time < end_time),
    CONSTRAINT ck_reservation_status CHECK (status IN ('PHONE_PENDING', 'CONFIRMED', 'CANCELLED', 'FAILED'))
);

CREATE INDEX ix_reservation_owner_date ON reservation (owner_public_id, appointment_date DESC);

CREATE TABLE processed_event (
    event_id VARCHAR(120) PRIMARY KEY,
    event_type VARCHAR(80) NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL
);
